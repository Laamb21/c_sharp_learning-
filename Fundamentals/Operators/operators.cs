//Arithmetic operators
//Addition
int sum = 5 + 5;
Console.WriteLine($"Addition: 5 + 5 = {sum}");
//Subtraction
int diff = 10 - 2;
Console.WriteLine($"Subtraction: 10 - 2 = {diff}");
//Multiplication
int mult = 3 * 3;
Console.WriteLine($"Mulitplication: 3 * 3 = {mult}");
//Division
int div = 20 / 4;
Console.WriteLine($"Division: 20 / 4 = {div}");
//Modulus
int mod = 10 % 2;
Console.WriteLine($"Modulus: 10 % 2 = {mod}");
